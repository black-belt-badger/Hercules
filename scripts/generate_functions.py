#!/usr/bin/env python3
"""Generate readable Java 17 F3-F10 sources with complete public Javadocs."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PKG = "io.github.blackbeltbadger.hercules"
LETTERS = "ABCDEFGHIJ"


def fn(args, result="R"):
    n = len(args)
    if n == 1:
        return f"Function<{args[0]}, {result}>"
    if n == 2:
        return f"BiFunction<{args[0]}, {args[1]}, {result}>"
    return f"F{n}<{', '.join([*args, result])}>"


def curry(args, result="R"):
    for arg in reversed(args):
        result = f"Function<{arg}, {result}>"
    return result


def javadoc(summary, type_params=(), params=(), returns=None):
    lines = ["    /**", f"     * {summary}"]
    if type_params or params or returns:
        lines.append("     *")
    for name, description in type_params:
        lines.append(f"     * @param <{name}> {description}")
    for name, description in params:
        lines.append(f"     * @param {name} {description}")
    if returns:
        lines.append(f"     * @return {returns}")
    lines.append("     */")
    return lines


def generate(n):
    args = list(LETTERS[:n])
    names = [a.lower() for a in args]
    types = ", ".join([*args, "R"])
    params = ", ".join(f"{a} {name}" for a, name in zip(args, names))
    call = ", ".join(names)
    type_docs = [(arg, f"argument {i + 1} type") for i, arg in enumerate(args)]
    argument_docs = [(name, f"argument {i + 1}") for i, name in enumerate(names)]
    lines = [
        "// Generated by scripts/generate_functions.py; edit the generator, not this file.",
        f"package {PKG};", "",
        "import java.util.Objects;",
        "import java.util.function.BiFunction;",
        "import java.util.function.Function;", "",
        "import lombok.NonNull;", "",
        "/**",
        f" * A function of {n} arguments, compatible with JDK unary and binary functions.",
        " *",
        " * <p>Transformations are lazy. Non-null callbacks are checked at composition",
        " * time; inputs and results follow JSpecify type-use nullness contracts.",
        " * User exceptions are propagated unchanged.",
        " *",
        *[f" * @param <{name}> {description}" for name, description in type_docs],
        " * @param <R> result type",
        " */",
        "@FunctionalInterface",
        f"public interface F{n}<{types}> {{", "",
    ]
    lines += javadoc(
        "Evaluate the function using all arguments.",
        params=argument_docs,
        returns="the computed result",
    ) + [f"    R apply({params});", ""]
    lines += javadoc(
        "Transform the result without evaluating the original function.",
        type_params=[("S", "new result type")],
        params=[("mapper", "result transformation, required at composition time")],
        returns="a lazily mapped function",
    ) + [
        f"    default <S> {fn(args, 'S')} map(@NonNull Function<? super R, ? extends S> mapper) {{",
        f"        return ({call}) -> mapper.apply(apply({call}));",
        "    }", "",
    ]
    lines += javadoc(
        "Reader-style bind; both functions receive the same arguments.",
        type_params=[("S", "new result type")],
        params=[("binder", "maps a result to another function with the same inputs")],
        returns="a lazily composed function",
    ) + [
        f"    default <S> {fn(args, 'S')} flatMap(",
        f"            @NonNull Function<? super R, ? extends {fn(args, 'S')}> binder) {{",
        f'        return ({call}) -> Objects.requireNonNull(binder.apply(apply({call})),',
        f'                "flatMap returned a null function").apply({call});',
        "    }", "",
    ]
    for k in range(1, n):
        lines += javadoc(
            f"Bind the first {k} arguments; evaluation is lazy." if k > 1 else "Bind the first argument; evaluation is lazy.",
            params=argument_docs[:k],
            returns=(f"a function accepting the remaining {n - k} arguments" if n-k > 1 else "a function accepting the remaining argument"),
        ) + [
            f"    default {fn(args[k:])} partial({', '.join(f'{a} {v}' for a, v in zip(args[:k], names[:k]))}) {{",
            f"        return ({', '.join(names[k:])}) -> apply({call});",
            "    }", "",
        ]
    for i, a in enumerate(args):
        target = args.copy()
        target[i] = "Z"
        transformed = names.copy()
        transformed[i] = f"before.apply({names[i]})"
        lines += javadoc(
            f"Transform argument {i + 1} prior to evaluation.",
            type_params=[("Z", f"new type of argument {i + 1}")],
            params=[("before", f"transformation to the original argument {i + 1} type")],
            returns="a function accepting the transformed argument",
        ) + [
            f"    default <Z> {fn(target)} compose{i+1}(",
            f"            @NonNull Function<? super Z, ? extends {a}> before) {{",
            f"        return ({call}) -> apply({', '.join(transformed)});",
            "    }", "",
        ]
    lines += javadoc(
        "Fully curry this function into nested JDK Function values.",
        returns="a curried function, evaluated when all arguments are supplied",
    ) + [
        f"    default {curry(args)} curried() {{",
        f"        return {' -> '.join(names)} -> apply({call});",
        "    }", "",
    ]
    lines += javadoc(
        "Uncurry nested JDK Function values.",
        type_params=[*type_docs, ("R", "result type")],
        params=[("function", "a curried function accepting all arguments")],
        returns="an uncurried multi-argument function",
    ) + [
        f"    static <{types}> {fn(args)} uncurry(@NonNull {curry(args)} function) {{",
        f"        return ({call}) -> function{''.join(f'.apply({v})' for v in names)};",
        "    }",
        "}", "",
    ]
    return "\n".join(lines)


def main():
    dest = ROOT / "src/main/java" / PKG.replace(".", "/")
    dest.mkdir(parents=True, exist_ok=True)
    for n in range(3, 11):
        (dest / f"F{n}.java").write_text(generate(n), encoding="utf8")
        print("Generated F" + str(n))


if __name__ == "__main__":
    main()
