#!/usr/bin/env python3
"""Check generated Java against fresh output without modifying the checkout.

Usage: python3 scripts/verify_generated.py [--self-test]
"""
import argparse
import difflib
from pathlib import Path
import shutil
import subprocess
import sys
from tempfile import TemporaryDirectory

GENERATORS = (
    "generate_functions.py",
    "generate_function_tests.py",
    "generate_validation_mapn.py",
)
OUTPUTS = (
    *(f"src/main/java/bbb/hercules/F{n}.java" for n in range(3, 11)),
    "src/test/java/bbb/hercules/HigherArityFunctionsTest.java",
    "src/main/java/bbb/hercules/ValidationApplicative.java",
)


def compare_generated(root: Path) -> list[str]:
    """Return diagnostics, or [] when checked-in generated content is current."""
    with TemporaryDirectory(prefix="hercules-generated-") as scratch:
        staged = Path(scratch)
        inputs = [*(f"scripts/{name}" for name in GENERATORS),
                  "src/main/java/bbb/hercules/ValidationApplicative.java"]
        for rel in inputs:
            source = root / rel
            if not source.is_file():
                return [f"Missing generator input: {rel}"]
            target = staged / rel
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(source, target)

        for generator in GENERATORS:
            result = subprocess.run(
                [sys.executable, "-B", str(staged / "scripts" / generator)],
                cwd=staged, capture_output=True, text=True, check=False,
            )
            if result.returncode:
                return [f"{generator} failed with exit {result.returncode}:\n"
                        f"{result.stdout}{result.stderr}"]

        differences = []
        for rel in OUTPUTS:
            checked_in, generated = root / rel, staged / rel
            if not checked_in.is_file():
                differences.append(f"Missing checked-in generated file: {rel}")
                continue
            if not generated.is_file():
                differences.append(f"Generator failed to produce: {rel}")
                continue
            actual, expected = checked_in.read_bytes(), generated.read_bytes()
            if actual != expected:
                diff = "".join(difflib.unified_diff(
                    actual.decode("utf-8").splitlines(keepends=True),
                    expected.decode("utf-8").splitlines(keepends=True),
                    fromfile=f"checked-in/{rel}",
                    tofile=f"generated/{rel}",
                ))
                differences.append(f"Generator drift: {rel}\n{diff}")
        return differences


def self_test(root: Path) -> None:
    """Prove the check detects drift in each generated artifact family."""
    with TemporaryDirectory(prefix="hercules-generator-test-") as scratch:
        isolated = Path(scratch)
        files = [*(f"scripts/{name}" for name in GENERATORS), *OUTPUTS]
        for rel in files:
            target = isolated / rel
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(root / rel, target)

        if errors := compare_generated(isolated):
            raise AssertionError("Baseline generated files disagree:\n" + "\n".join(errors))

        cases = (
            ("src/main/java/bbb/hercules/F3.java",
             "A function of 3 arguments", "A different function of 3 arguments",
             "F3.java"),
            ("src/test/java/bbb/hercules/HigherArityFunctionsTest.java",
             "Generated by scripts", "Hand-edited despite scripts",
             "HigherArityFunctionsTest.java"),
            ("src/main/java/bbb/hercules/ValidationApplicative.java",
             "Combine 3 independent validations", "Combine 3 altered validations",
             "ValidationApplicative.java"),
            ("scripts/generate_functions.py",
             "A function of {n} arguments", "A changed function of {n} arguments",
             "F3.java"),
            ("scripts/generate_function_tests.py",
             "class HigherArityFunctionsTest", "class UnexpectedFunctionTests",
             "HigherArityFunctionsTest.java"),
            ("scripts/generate_validation_mapn.py",
             "Combine {arity} independent validations", "Combine {arity} changed validations",
             "ValidationApplicative.java"),
        )
        for rel, original, replacement, expected in cases:
            path = isolated / rel
            before = path.read_text(encoding="utf-8")
            if before.count(original) != 1:
                raise AssertionError(f"Expected one fixture marker in {rel}")
            path.write_text(before.replace(original, replacement), encoding="utf-8")
            try:
                errors = compare_generated(isolated)
                if not any(expected in error for error in errors):
                    raise AssertionError(
                        f"Failed to catch deliberate drift in {rel}: {errors}"
                    )
                print(f"PASS: detects deliberate drift in {rel}")
            finally:
                path.write_text(before, encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--self-test", action="store_true",
                        help="also prove intentional drift is detected")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    errors = compare_generated(root)
    if errors:
        for error in errors:
            print(error, file=sys.stderr)
        return 1
    print(f"PASS: {len(OUTPUTS)} generated Java outputs match their generators")
    if args.self_test:
        self_test(root)
    return 0


if __name__ == "__main__":
    sys.exit(main())
